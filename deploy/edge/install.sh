#!/usr/bin/env bash
# Installs (or updates) the shared edge proxy in /opt/edge and starts it. Safe to re-run.
#   TABLEBOT_HOST=tablebot.example.com TUTORHUB_HOST=tutorhub.example.com \
#     bash /opt/tutorhub/deploy/edge/install.sh [--no-start] [--copy-certs]
# Hosts are remembered in /opt/edge/edge.env, so later runs need no variables. Set a host to
# "-" to remove its site. --no-start writes files and the network but does not start the edge
# (it would fail while another Caddy holds 80/443). --copy-certs copies TableBot's existing
# certificates (volume tablebot_caddy_data) into edge_data before starting.
# Env overrides (for testing): EDGE_DIR (default /opt/edge), CADDY_IMAGE (default caddy:2).
set -euo pipefail

EDGE_DIR="${EDGE_DIR:-/opt/edge}"
CADDY_IMAGE="${CADDY_IMAGE:-caddy:2}"
SRC_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

step() { printf '\n==> %s\n' "$*"; }
fail() { printf '\nERROR: %s\n' "$*" >&2; exit 1; }

start=1
copy_certs=0
for arg in "$@"; do
  case "$arg" in
    --no-start) start=0 ;;
    --copy-certs) copy_certs=1 ;;
    *) fail "unknown option $arg (use --no-start and/or --copy-certs)" ;;
  esac
done

[[ "$(id -u)" -ne 0 ]] || fail "do not run as root; run it as your normal user (who is in the docker group)."
docker info >/dev/null 2>&1 || fail "cannot talk to Docker. Is your user in the docker group? (log out and back in after adding it)"

step "Docker network \"edge\""
if docker network inspect edge >/dev/null 2>&1; then
  echo "already exists"
else
  docker network create edge >/dev/null
  echo "created"
fi

step "Stack files in $EDGE_DIR"
if [[ ! -d "$EDGE_DIR" ]]; then
  sudo install -d -o "$(id -un)" -g "$(id -gn)" "$EDGE_DIR"
fi
install -d "$EDGE_DIR/sites"
install -m 644 "$SRC_DIR/docker-compose.yml" "$EDGE_DIR/docker-compose.yml"
install -m 644 "$SRC_DIR/Caddyfile" "$EDGE_DIR/Caddyfile"
echo "copied docker-compose.yml and Caddyfile"

# Hosts: environment wins, then the saved values.
saved_tablebot="" saved_tutorhub=""
if [[ -f "$EDGE_DIR/edge.env" ]]; then
  saved_tablebot="$(grep -E '^TABLEBOT_HOST=' "$EDGE_DIR/edge.env" | cut -d= -f2- || true)"
  saved_tutorhub="$(grep -E '^TUTORHUB_HOST=' "$EDGE_DIR/edge.env" | cut -d= -f2- || true)"
fi
tablebot_host="${TABLEBOT_HOST:-$saved_tablebot}"
tutorhub_host="${TUTORHUB_HOST:-$saved_tutorhub}"
[[ "$tablebot_host" == "-" ]] && tablebot_host=""
[[ "$tutorhub_host" == "-" ]] && tutorhub_host=""
printf 'TABLEBOT_HOST=%s\nTUTORHUB_HOST=%s\n' "$tablebot_host" "$tutorhub_host" >"$EDGE_DIR/edge.env"

step "Site files in $EDGE_DIR/sites"
# write_site HOST ALIAS writes sites/HOST.caddy forwarding HOST to ALIAS:80.
write_site() {
  local host="$1" alias="$2"
  [[ "$host" =~ ^[A-Za-z0-9.-]+$ ]] || fail "host \"$host\" must be a plain domain name like tutorhub.example.com"
  cat >"$EDGE_DIR/sites/$host.caddy" <<SITE
# Generated by install.sh: $host -> $alias (do not edit; re-run install.sh instead)
$host {
	encode zstd gzip
	reverse_proxy $alias:80
}
SITE
  echo "$host -> $alias:80"
}
rm -f "$EDGE_DIR"/sites/*.caddy
[[ -n "$tablebot_host" ]] && write_site "$tablebot_host" tablebot-web
[[ -n "$tutorhub_host" ]] && write_site "$tutorhub_host" tutorhub-web
if [[ -z "$tablebot_host" && -z "$tutorhub_host" ]]; then
  echo "no hosts set (TABLEBOT_HOST / TUTORHUB_HOST): the edge will serve nothing"
fi

step "Validating the Caddy config"
docker run --rm \
  -v "$EDGE_DIR/Caddyfile:/etc/caddy/Caddyfile:ro" \
  -v "$EDGE_DIR/sites:/etc/caddy/sites:ro" \
  "$CADDY_IMAGE" caddy validate --config /etc/caddy/Caddyfile --adapter caddyfile 2>&1 | tail -n 3
echo "config is valid"

compose() { docker compose -p edge -f "$EDGE_DIR/docker-compose.yml" "$@"; }

if [[ "$copy_certs" -eq 1 ]]; then
  step "Copying TableBot certificates into edge_data"
  if docker volume inspect tablebot_caddy_data >/dev/null 2>&1; then
    docker volume create edge_data >/dev/null
    # -n: never overwrite certificates the edge already has.
    docker run --rm -v tablebot_caddy_data:/from:ro -v edge_data:/to alpine:3 \
      sh -c 'if [ -d /from/caddy ]; then mkdir -p /to/caddy && cp -an /from/caddy/. /to/caddy/ && echo copied; else echo "nothing to copy"; fi'
  else
    echo "volume tablebot_caddy_data not found, skipping"
  fi
fi

if [[ "$start" -eq 0 ]]; then
  step "Not starting the edge (--no-start). Start it later with: bash $SRC_DIR/install.sh"
  exit 0
fi

step "Starting the edge"
if ! compose up -d --remove-orphans; then
  fail "the edge did not start. If port 80/443 is taken, another Caddy still publishes it: docker ps --format '{{.Names}} {{.Ports}}' | grep -E ':(80|443)->'"
fi
compose ps

step "Checks (certificates can take a minute on first start)"
for host in $tablebot_host $tutorhub_host; do
  echo "  curl -I https://$host"
done
for host in $tablebot_host $tutorhub_host; do
  sleep 2
  printf '\n%s: ' "$host"
  curl -sSI --max-time 20 --resolve "$host:443:127.0.0.1" "https://$host" | head -n 1 || echo "not answering yet (retry in a minute; logs: docker compose -p edge -f $EDGE_DIR/docker-compose.yml logs edge)"
done
